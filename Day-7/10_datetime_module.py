# 3. datetime Module
import datetime

now = datetime.datetime.now()
print("Full Timestamp: ,now")

print("Date and Time:",now)
print("Date:", now.date())
print("Year:", now.year)
print("Time ", now.time())
print("Day", now.day)
print("Hour", now.hour)
print("Minute", now.minute)
print("Second", now.second)
